#!/usr/bin/env python3
"""Generates addons/DeckHUD/FocusAuraSpells.lua: every rank's spell ID for the buffs the focus
frame's aura row can show.

The game's aura containers filter buffs by exact spell ID (candidateFilters.includeSpellIDs), and
another player may have cast any rank, but the client can't list a spell's ranks by name. So the
IDs come from WoW: Forever's own data tables, published per client build on wago.tools (product
"wowf"). Run it after a Forever update that adds or changes buffs:

    python3 deck-setup/make-focus-aura-spells.py [--build 1.60.1.70888]

Without --build it uses the newest wowf build on wago.tools. The list of buffs is BUFFS below:
what someone might put on a player you're healing, by class.
"""
import argparse, csv, io, json, os, urllib.request

# (class, spell name). Names must match Forever's spell names exactly.
BUFFS = [
    ("Priest", "Power Word: Shield"), ("Priest", "Renew"), ("Priest", "Prayer of Mending"),
    ("Priest", "Power Word: Fortitude"), ("Priest", "Prayer of Fortitude"), ("Priest", "Divine Spirit"),
    ("Priest", "Prayer of Spirit"), ("Priest", "Shadow Protection"), ("Priest", "Prayer of Shadow Protection"),
    ("Priest", "Fear Ward"), ("Priest", "Power Infusion"), ("Priest", "Pain Suppression"),
    ("Priest", "Contingency Plan"),
    ("Druid", "Rejuvenation"), ("Druid", "Regrowth"), ("Druid", "Lifebloom"), ("Druid", "Wild Growth"),
    ("Druid", "Mark of the Wild"), ("Druid", "Gift of the Wild"), ("Druid", "Thorns"), ("Druid", "Innervate"),
    ("Druid", "Abolish Poison"),
    ("Shaman", "Riptide"), ("Shaman", "Earth Shield"),
    ("Paladin", "Blessing of Might"), ("Paladin", "Blessing of Wisdom"), ("Paladin", "Blessing of Kings"),
    ("Paladin", "Blessing of Salvation"), ("Paladin", "Blessing of Light"), ("Paladin", "Blessing of Sanctuary"),
    ("Paladin", "Greater Blessing of Might"), ("Paladin", "Greater Blessing of Wisdom"),
    ("Paladin", "Greater Blessing of Kings"), ("Paladin", "Greater Blessing of Salvation"),
    ("Paladin", "Blessing of Protection"), ("Paladin", "Blessing of Freedom"), ("Paladin", "Blessing of Sacrifice"),
    ("Paladin", "Sacred Shield"), ("Paladin", "Oath of Light"), ("Paladin", "Light's Vigil"),
    ("Mage", "Arcane Intellect"), ("Mage", "Arcane Brilliance"), ("Mage", "Amplify Magic"), ("Mage", "Dampen Magic"),
    ("Warlock", "Unending Breath"), ("Warlock", "Detect Invisibility"), ("Warlock", "Soulstone Resurrection"),
]

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "addons", "DeckHUD", "FocusAuraSpells.lua")


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode("utf-8")


def latest_build():
    builds = json.loads(fetch("https://wago.tools/api/builds"))
    return builds["wowf"][0]["version"]


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--build", help="client build, e.g. 1.60.1.70888 (default: newest wowf on wago.tools)")
    a = ap.parse_args()
    build = a.build or latest_build()
    names = {}
    for row in csv.DictReader(io.StringIO(fetch("https://wago.tools/db2/SpellName/csv?build=" + build))):
        names.setdefault(row["Name_lang"], []).append(int(row["ID"]))

    lines = [
        "-- Generated by deck-setup/make-focus-aura-spells.py from WoW: Forever's data tables (build %s)." % build,
        "-- Don't edit: change BUFFS in the script and run it again.",
        "-- Every rank's spell ID for each buff, since the aura containers filter by exact ID.",
        "local _, ns = ...",
        "ns.FOCUS_AURA_SPELLS = {",
    ]
    missing = []
    for cls, name in BUFFS:
        ids = sorted(names.get(name, []))
        if not ids:
            missing.append(name)
            continue
        lines.append('    { class = "%s", name = %s, ids = { %s } },' % (cls, json.dumps(name), ", ".join(map(str, ids))))
    lines.append("}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s (%d buffs, build %s)" % (os.path.normpath(OUT), len(BUFFS) - len(missing), build))
    if missing:
        print("not in this build:", ", ".join(missing))


if __name__ == "__main__":
    main()
